# Builds jack_capture as a universal binary (arm64 + x86_64) from upstream/ and patches/,
# linked statically with libsndfile and its codecs (FLAC, Ogg Vorbis, Opus, MP3) and with liblo.
# Only libjack stays dynamic, linked by its full path.
# The libraries must be built first, with libs/<name>/build_universal.sh, in <libs build dir>.
# Usage: build_universal.sh [libs build dir] [output dir]
#        (defaults: libs/build, jack_capture/build)
# Environment: JACK_PREFIX = where the JACK headers and libjack are installed (default /usr/local).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
. "$here/../libs/common.sh"
ub_setup "$here/upstream" "${1:-$here/../libs/build}"
out=${2:-$here/build}
mkdir -p "$out"; out=$(cd "$out" && pwd)
jack_prefix=${JACK_PREFIX:-/usr/local}

# Expose only JACK to the compiler: other libraries installed next to it must not be picked up.
jack=$UB_WORK/jack
mkdir -p "$jack/include" "$jack/lib"
ln -s "$jack_prefix/include/jack" "$jack/include/jack"
ln -s "$jack_prefix/lib/libjack.dylib" "$jack/lib/libjack.dylib"

for arch in $UB_ARCHS; do
  prefix=$UB_OUT/$arch
  dir=$UB_WORK/jack_capture_$arch
  rm -rf "$dir"; cp -R "$UB_SRC" "$dir"
  ub_patch "$dir"
  sndfile_libs=$(ub_env "$arch" pkg-config --static --libs sndfile)
  ( cd "$dir"
    ub_env "$arch" make CC=clang \
      CFLAGS="-arch $arch -I$prefix/include -I$jack/include" \
      LDFLAGS="-arch $arch -L$prefix/lib -L$jack/lib" \
      LINKFLAGS="-arch $arch -L$prefix/lib -L$jack/lib $sndfile_libs -ljack -lm -lpthread" \
      jack_capture )
  # The format list is generated by probing the compiler: if the probes fail, jack_capture
  # silently falls back to WAV for every format. Do not ship such a build.
  for f in SF_FORMAT_AIFF SF_FORMAT_FLAC SF_FORMAT_CAF SF_FORMAT_W64 SF_FORMAT_RF64 SF_FORMAT_VORBIS SF_FORMAT_OPUS; do
    grep -q "$f" "$dir/setformat.c" || { echo "error: $f missing from setformat.c ($arch)" >&2; exit 1; }
  done
  mkdir -p "$UB_WORK/bin_$arch"
  cp "$dir/jack_capture" "$UB_WORK/bin_$arch/jack_capture"
done

lipo -create "$UB_WORK"/bin_arm64/jack_capture "$UB_WORK"/bin_x86_64/jack_capture -output "$out/jack_capture"
strip -x "$out/jack_capture"
lipo -info "$out/jack_capture"
